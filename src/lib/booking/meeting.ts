import type { Booking } from "@prisma/client";
import { getSetting } from "@/lib/settings";
import { createCalendarEvent } from "./google-calendar";
import { publishTelegramBooking } from "./telegram";
import { buildWhatsAppLink } from "./whatsapp";
import { createZoomMeeting } from "./zoom";
import { formatDateTimeInZone, HOST_TIME_ZONE } from "./time";
import { Platform, platformLabel } from "./types";

export interface MeetingOutcome {
  meetingUrl: string | null;
  meetingId: string | null;
  hostUrl: string | null;
  meetingPassword: string | null;
  calendarEventId: string | null;
  calendarHtmlLink: string | null;
  warnings: string[];
}

export function meetingSummary(booking: Booking): string {
  return `Meeting with ${booking.requesterName} — ${booking.topic}`;
}

export function buildMeetingDescription(
  booking: Booking,
  meetingUrl: string | null,
): string {
  const lines = [
    `Topic: ${booking.topic}`,
    `Requested by: ${booking.requesterName} (${booking.requesterEmail})`,
    booking.requesterCompany ? `Company: ${booking.requesterCompany}` : "",
    `Platform: ${platformLabel(booking.platform)}`,
    `Duration: ${booking.durationMinutes} minutes`,
    meetingUrl ? `Join link: ${meetingUrl}` : "",
    booking.notes ? `\nNotes:\n${booking.notes}` : "",
    "",
    "Booked through https://kidus-portfolio-gray.vercel.app",
  ];

  return lines.filter(Boolean).join("\n");
}

export function buildWhatsAppMessage(booking: Booking, meetingUrl: string | null): string {
  const when = formatDateTimeInZone(booking.startsAt, HOST_TIME_ZONE);
  const lines = [
    `Hi ${booking.requesterName}, this is Kidus Amanuel.`,
    `Looking forward to our meeting: ${booking.topic}.`,
    `When: ${when} (East Africa Time)`,
    meetingUrl ? `Meeting link: ${meetingUrl}` : "",
    "",
    "See you soon!",
  ];

  return lines.filter(Boolean).join("\n");
}

/**
 * Turn an accepted booking into real meeting infrastructure:
 * a platform link (Zoom / WhatsApp / Telegram / Google Meet) plus a Google
 * Calendar event with the visitor as an attendee, so Google emails the
 * invitation to both sides and both get reminders.
 */
export async function finalizeBookingMeeting(
  booking: Booking,
  options: { manualMeetingUrl?: string | null } = {},
): Promise<MeetingOutcome> {
  const warnings: string[] = [];

  let meetingUrl: string | null = options.manualMeetingUrl?.trim() || null;
  let meetingId: string | null = null;
  let hostUrl: string | null = null;
  let meetingPassword: string | null = null;

  const platform = booking.platform as Platform;

  if (!meetingUrl) {
    if (platform === "ZOOM") {
      const zoom = await createZoomMeeting({
        topic: meetingSummary(booking),
        start: booking.startsAt,
        durationMinutes: booking.durationMinutes,
        timeZone: HOST_TIME_ZONE,
        agenda: booking.notes ?? undefined,
      });

      if (zoom.ok && zoom.meeting) {
        meetingUrl = zoom.meeting.joinUrl;
        meetingId = zoom.meeting.id;
        hostUrl = zoom.meeting.startUrl;
        meetingPassword = zoom.meeting.password ?? null;
      } else {
        warnings.push(zoom.error ?? "Zoom meeting could not be created.");
      }
    } else if (platform === "WHATSAPP") {
      const link = buildWhatsAppLink(booking.requesterPhone ?? "", buildWhatsAppMessage(booking, null));
      if (link) {
        meetingUrl = link;
      } else {
        warnings.push("WhatsApp needs the visitor's phone number in international format.");
      }
    } else if (platform === "TELEGRAM") {
      const chatId = await getSetting("TELEGRAM_CHAT_ID");

      const telegram = await publishTelegramBooking({
        chatId: chatId ?? "",
        bookingId: booking.id,
        topic: booking.topic,
        attendeeName: booking.requesterName,
        startsAtLabel: formatDateTimeInZone(booking.startsAt, HOST_TIME_ZONE),
        expiresAt: new Date(booking.endsAt.getTime() + 60 * 60 * 1000),
      });

      if (telegram.inviteLink) {
        meetingUrl = telegram.inviteLink;
      } else if (telegram.chatLink) {
        meetingUrl = telegram.chatLink;
      }

      if (!telegram.ok) {
        warnings.push(telegram.error ?? "Telegram booking could not be published.");
      } else if (telegram.error) {
        warnings.push(telegram.error);
      }
    }
  }

  // Google Calendar event. For Google Meet the link is generated by this very
  // call through `conferenceData`.
  const wantsMeetLink = platform === "GOOGLE_MEET" && !options.manualMeetingUrl?.trim();

  const event = await createCalendarEvent({
    summary: meetingSummary(booking),
    description: buildMeetingDescription(booking, meetingUrl),
    location: meetingUrl ?? "Video call",
    start: booking.startsAt,
    end: booking.endsAt,
    timeZone: HOST_TIME_ZONE,
    attendeeEmail: booking.requesterEmail,
    attendeeName: booking.requesterName,
    requestMeetLink: wantsMeetLink,
  });

  let calendarEventId: string | null = null;
  let calendarHtmlLink: string | null = null;

  if (event.ok) {
    calendarEventId = event.eventId ?? null;
    calendarHtmlLink = event.htmlLink ?? null;
    if (wantsMeetLink && event.meetUrl) meetingUrl = event.meetUrl;
  } else {
    warnings.push(event.error ?? "Google Calendar event could not be created.");
  }

  return {
    meetingUrl,
    meetingId,
    hostUrl,
    meetingPassword,
    calendarEventId,
    calendarHtmlLink,
    warnings,
  };
}
